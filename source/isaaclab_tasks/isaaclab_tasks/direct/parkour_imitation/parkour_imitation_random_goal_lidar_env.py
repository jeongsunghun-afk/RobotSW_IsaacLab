# Gracefully disabled if file is missing (warn, no crash).
_BODY_OCC_GRID_PATH: Path = (
    Path(__file__).parents[5] / "_workspace/parkour_imitation_lidar/r1_throughput/body_occ_azel_grid.npy"
)

# Steps at which the occupancy-grid diagnostic reports, mirroring the [VoxelOccupancy] cadence in
# ``parkour_env``.  Treated as thresholds rather than exact matches — see
# ``_log_lidar_grid_diagnostics``.
_LIDAR_GRID_DIAG_STEPS: tuple[int, ...] = (5, 50, 150, 300, 500, 2000, 5000, 9000)


class Go2ParkourImitationRandomGoalLidarEnv(Go2ParkourImitationRandomGoalEnv):
    """Go2 ParkourImitation-RandomGoal env with Livox Mid-360 LiDAR (R2 range image).

    Additions over the parent env:
        1. ``self._mid360`` (``LidarSensor``) — created in ``_setup_scene``.
        2. ``obs["lidar"]`` shape (N, K*C*H*W) — range-image frame stack.
           Buffer layout (N, K, C=2, H, W) flattened via ``.reshape(N, -1)``.
           ch0 = range_norm, ch1 = hit_mask (see module docstring for full contract).
        3. ``self._lidar_frame_buf`` (N, K, 2, H, W) — ring buffer; reset in _reset_idx.

    Policy obs dimensions (policy/scan/priv_explicit/priv_latent/history/amp) are
    byte-identical to ``Go2ParkourImitationRandomGoalEnv``.
    """

    cfg: ParkourImitationRandomGoalLidarEnvCfg

    # ------------------------------------------------------------------
    # Scene setup
    # ------------------------------------------------------------------

    def _setup_scene(self) -> None:
        """Create all base sensors / terrain, then append the Mid-360 LidarSensor."""
        super()._setup_scene()

        # Mount overrides are re-applied here, not only in the cfg's __post_init__, because
        # hydra applies its overrides (``env_cfg.from_dict``) AFTER the cfg is constructed —
        # so a ``env.lidar_mount_pitch_deg=25`` on the command line would otherwise never reach
        # ``mid360_lidar.offset``.  ``resolve_lidar_mount`` is idempotent (it computes the
        # offset from the angle, never from the current offset), so running it twice is safe.
        resolve_lidar_mount(self.cfg)

        # LidarSensor resolves its prim_path regex lazily at sim-start, so appending
        # after clone_environments() is safe (same pattern as parkour height_scanner).
        # Instantiate through ``class_type`` so a cfg subclass (e.g.
        # :class:`~isaaclab_tasks.direct.parkour_imitation.mid360_rolling_lidar.Mid360RollingLidarSensorCfg`)
        # gets its own sensor class.  The core cfg's default is a ``"module:Class"`` string,
        # which is not resolved here — that path keeps the historical ``LidarSensor``.
        # ``"module:Class"`` strings are resolved here (lazily, after app launch — the class pulls
        # in ``isaaclab_physx``); the core default ``"{DIR}.lidar_sensor:LidarSensor"`` and any
        # other unresolvable string keep the historical ``LidarSensor``.
        sensor_cls = self.cfg.mid360_lidar.class_type
        if isinstance(sensor_cls, str) and ":" in sensor_cls and not sensor_cls.startswith("{DIR}"):
            mod_name, cls_name = sensor_cls.split(":", 1)
            sensor_cls = getattr(importlib.import_module(mod_name), cls_name)
        self._mid360 = (
            sensor_cls(self.cfg.mid360_lidar) if isinstance(sensor_cls, type) else LidarSensor(self.cfg.mid360_lidar)
        )
        self.scene.sensors["mid360_lidar"] = self._mid360

        # Static body self-occlusion az/el grid (nominal upright pose).
        # Computed once by compute_body_mask.py (body-only raycast + min_range offset).
        # Runtime masking is direction-based (not per-index) — immune to any residual
        # sensor rotation accumulation.
        self._body_occ_grid: torch.Tensor | None = None
        self._body_occ_res: float = 1.0  # degrees per grid bin (inferred from grid shape)
        self._body_occ_n_el: int = 180  # number of elevation bins
        self._body_occ_n_az: int = 360  # number of azimuth bins
        if not getattr(self.cfg, "lidar_use_body_occ_mask", True):
            # Real-sensor arm: the deployment pipeline never applies this mask.  It drops
            # returns closer than the blind range instead, which removes the body for free
            # and does not assume the nominal upright pose the grid was baked at.
            print("[LidarEnv] body self-occlusion mask: disabled (cfg)")
            return
        _cfg_path = getattr(self.cfg, "body_occ_grid_path", None)
        self._body_occ_grid_path: Path = Path(_cfg_path) if _cfg_path else _BODY_OCC_GRID_PATH
        if self._body_occ_grid_path.exists():
            grid_np = np.load(str(self._body_occ_grid_path))
            self._body_occ_grid = torch.as_tensor(grid_np, dtype=torch.bool, device=self.device)
            self._body_occ_n_el, self._body_occ_n_az = grid_np.shape
            self._body_occ_res = 180.0 / self._body_occ_n_el
            print(
                f"[LidarEnv] body self-occlusion grid: {self._body_occ_grid_path} "
                f"({int(grid_np.sum())} / {grid_np.size} bins occluded)"
            )
        else:
            warnings.warn(
                f"Body self-occlusion grid not found at {self._body_occ_grid_path}. "
                "Run _workspace/parkour_imitation_lidar/r1_throughput/compute_body_mask.py "
                "to generate it.  Mask disabled (no body occlusion applied).",
                stacklevel=2,
            )

    # ------------------------------------------------------------------
    # R2 init — frame-stack ring buffer
    # ------------------------------------------------------------------

    def __init__(self, cfg: ParkourImitationRandomGoalLidarEnvCfg, render_mode: str | None = None, **kwargs):
        super().__init__(cfg, render_mode, **kwargs)

        # Frame-stack ring buffer: (N, K, C=2, H, W), float32, zero-initialised.
        # Newest frame at k=0 (contract); older frames at k=1..K-1.
        # Flattened to (N, K*C*H*W) as obs["lidar"] via .reshape(N, -1) (C-order).
        # r2-net recovers the layout via obs.reshape(N, K*C, H, W) → kc = k*C + c.
        K = cfg.lidar_frame_stack
        H = cfg.lidar_image_h
        W = cfg.lidar_image_w
        self._lidar_frame_buf: torch.Tensor = torch.zeros(
            self.num_envs,
            K,
            2,
            H,
            W,
            device=self.device,
            dtype=torch.float32,
        )

        # Metric-grid geometry for the occupancy representation (rung A1-0).  Deliberately the
        # SAME grid as the teacher's voxel input — same bounds, same 0.1 m resolution, same
        # yaw-aligned origin at the clearance mount — so the two are directly comparable and the
        # grid can later serve as the auxiliary-loss target's coordinate system.  A default
        # VoxelOccupancyCfg is constructed rather than reading the parent's ``_voxel_cfg``, which
        # only exists when the voxel scanner is enabled; nothing here mutates that config or
        # touches ``fill_voxel_grid`` (its output feeds the frozen teacher).
        self._lidar_grid_cfg: VoxelOccupancyCfg = VoxelOccupancyCfg()
        self._lidar_grid_shape: tuple[int, int, int] = voxel_grid_shape(self._lidar_grid_cfg)
        self._lidar_grid_lo: torch.Tensor = torch.tensor(
            [self._lidar_grid_cfg.x_range[0], self._lidar_grid_cfg.y_range[0], self._lidar_grid_cfg.z_range[0]],
            device=self.device,
            dtype=torch.float32,
        )
        # Cell centres in the grid's own frame, at lo + i*res (matching fill_voxel_grid's
        # round((p - lo)/res) indexing).  Precomputed because the accumulator warp evaluates them
        # every sensor tick.
        _nx, _ny, _nz = self._lidar_grid_shape
        _res = self._lidar_grid_cfg.resolution
        _ii = torch.meshgrid(
            torch.arange(_nx, device=self.device, dtype=torch.float32),
            torch.arange(_ny, device=self.device, dtype=torch.float32),
            torch.arange(_nz, device=self.device, dtype=torch.float32),
            indexing="ij",
        )
        self._lidar_grid_centres: torch.Tensor = self._lidar_grid_lo + torch.stack(_ii, dim=-1) * _res

        # Base-frame offset from the grid origin (clearance mount) to the Mid-360 mount, so a
        # ray's endpoint is grid_origin -> mount -> d * direction.
        self._lidar_grid_origin_shift: torch.Tensor = torch.tensor(
            cfg.mid360_lidar.offset.pos, device=self.device, dtype=torch.float32
        ) - torch.tensor([0.0, 0.0, cfg.lidar_grid_origin_z], device=self.device, dtype=torch.float32)

        # Accumulator state (rung A1-1).  Allocated unconditionally: (1024, 27, 21, 13) float32 is
        # 30 MB, small enough that gating it would cost more in branching than it saves.
        self._lidar_grid_acc: torch.Tensor = torch.zeros(
            self.num_envs, _nx, _ny, _nz, device=self.device, dtype=torch.float32
        )
        # Pose of the grid frame at the accumulator's last update, used to transport it forward.
        self._lidar_grid_prev_pos: torch.Tensor = torch.zeros(self.num_envs, 3, device=self.device)
        self._lidar_grid_prev_yaw: torch.Tensor = torch.zeros(self.num_envs, device=self.device)
        # Index of the next milestone in _LIDAR_GRID_DIAG_STEPS the diagnostic has yet to report.
        self._lidar_grid_diag_next: int = 0

        # ------------------------------------------------------------------
        # Rolling world-anchored store (cfg.lidar_grid_accumulate_mode == "rolling")
        # ------------------------------------------------------------------
        # Allocated only in rolling mode: at 1280 envs the store is 47*47*15 = 33,135 cells,
        # i.e. 170 MB float32, which is worth paying for only when it is read.
        self._lidar_store_shape: tuple[int, int, int] | None = None
        if getattr(cfg, "lidar_grid_accumulate_mode", "warp") == "rolling":
            self._setup_rolling_store(cfg)

        # Per-env "the stack has not been filled since the last reset" flag, consumed by the
        # first push after a reset when cfg.lidar_fill_stack_on_reset is set.  Initialised True
        # so the very first push of an episode fills every slot instead of leaving K-1 of them
        # at the zero frame, which decodes as geometry touching the sensor (ch0 = 0.0) rather
        # than as an empty bin (ch0 = 1.0).  Allocated unconditionally — it costs N bytes and
        # keeps _reset_idx branch-free.
        self._lidar_stack_needs_fill: torch.Tensor = torch.ones(self.num_envs, dtype=torch.bool, device=self.device)

        # Sensor-rate push cadence (default OFF — activated via cfg.lidar_stack_at_sensor_rate).
        #
        # Background: LidarSensorCfg inherits update_period=0.0 from SensorBaseCfg, so the
        # sensor's _is_outdated gate fires on EVERY physics step regardless of update_frequency.
        # With step_dt=0.02 s and K=3, per-step push means the ring buffer spans only 0.06 s of
        # temporal context — the three slots carry near-identical content.
        #
        # When True, each env's ring buffer is pushed only once every
        #   push_every = round(1 / (update_frequency * step_dt))
        # env steps (=5 at 10 Hz / 0.02 s), so K=3 slots span 3x0.1 s = 0.3 s.
        # Non-push steps hold the previous buffer unchanged, matching real 10 Hz deployment.
        #
        # Mechanism: per-env int32 step counter (_lidar_push_ctr).  Initialized to push_every
        # (not 0) so the first push fires on the very first control step after init/reset,
        # matching the sensor's _is_outdated=True-on-reset behaviour.
        if cfg.lidar_stack_at_sensor_rate:
            self._lidar_push_every: int = max(1, round(1.0 / (cfg.mid360_lidar.update_frequency * self.step_dt)))
            # Initialise at push_every -> triggers a push on the first step (before first sensor cycle).
            self._lidar_push_ctr: torch.Tensor = torch.full(
                (self.num_envs,),
                self._lidar_push_every,
                dtype=torch.int32,
                device=self.device,
            )

    def _setup_rolling_store(self, cfg: ParkourImitationRandomGoalLidarEnvCfg) -> None:
        """Allocate the rolling store and derive its geometry from ``cfg``.

        Split out of ``__init__`` so a diagnostic can build a second, independently configured
        store on the same env — the shadow comparison that scores several carving rules against
        the live accumulator on identical frames needs one store per variant.

        Args:
            cfg: Config to read the store geometry and free-space settings from.  Not necessarily
                ``self.cfg``: a shadow passes a shim with the variant's overrides.
        """
        res = self._lidar_grid_cfg.resolution
        nx, ny, nz = self._lidar_grid_shape
        radius = float(cfg.lidar_grid_store_radius)
        sxy = int(round(radius / res)) * 2 + 1
        zm = int(cfg.lidar_grid_store_z_margin_cells)
        sz = nz + 2 * zm
        self._lidar_store_shape = (sxy, sxy, sz)
        self._lidar_store_lo: torch.Tensor = torch.tensor(
            [-(sxy // 2) * res, -(sxy // 2) * res, self._lidar_grid_cfg.z_range[0] - zm * res],
            device=self.device,
            dtype=torch.float32,
        )
        self._lidar_grid_store: torch.Tensor = torch.zeros(
            self.num_envs, sxy, sxy, sz, device=self.device, dtype=torch.float32
        )
        # World position the store's lattice is anchored to: the grid origin rounded to the cell
        # lattice.  The sub-cell residual ``origin - snap`` is never accumulated here; it is
        # applied once, at readout.
        self._lidar_store_snap: torch.Tensor = torch.zeros(self.num_envs, 3, device=self.device)
        # Scroll destination, grown on demand to the largest ticking subset seen.  Declared here
        # rather than created lazily on first use so that an object which delegates unknown
        # attributes to another env (the shadow accumulators the diagnostics build) gets its own
        # buffer instead of silently scribbling in the env's.
        self._lidar_store_scratch: torch.Tensor | None = None
        # Readout held between sensor ticks, so a non-ticking control step returns the same
        # observation the warp path would hold rather than re-sampling a map that has not changed.
        self._lidar_store_readout: torch.Tensor = torch.zeros(
            self.num_envs, nx * ny * nz, device=self.device, dtype=torch.float32
        )
        # Samples per ray for free-space carving.  Bounded by the READOUT box, not by the store:
        # the store is 2.3 m in radius but only the 27x21x13 readout box is ever handed to the
        # policy, so a sample beyond the box's far corner cannot affect any observation this tick
        # and the ones it would affect later get carved on the tick they enter the box.  The
        # bound is the distance from the Mid-360 mount to the box's far corner, plus one cell.
        cg = self._lidar_grid_cfg
        m_off = self._lidar_grid_origin_shift  # grid origin -> mount, base frame
        d_box = [
            max(abs(rng[0] - float(m_off[i])), abs(rng[1] - float(m_off[i])))
            for i, rng in enumerate((cg.x_range, cg.y_range, cg.z_range))
        ]
        reach = math.sqrt(sum(v * v for v in d_box)) + res
        step_fs = float(cfg.lidar_grid_free_space_step)
        self._lidar_free_max_samples: int = max(1, int(math.ceil(reach / step_fs)))
        if self._lidar_free_max_samples > 50:
            raise ValueError(
                f"free-space carving would need {self._lidar_free_max_samples} samples per ray "
                f"(readout box reach {reach:.2f} m, step {step_fs} m); raise the step."
            )

    # ------------------------------------------------------------------
    # R2 reset — zero frame buffer for reset envs
    # ------------------------------------------------------------------

    def _reset_idx(self, env_ids: torch.Tensor | None) -> None:
        """Delegate to parent reset; zero the lidar frame buffer for reset envs."""
        super()._reset_idx(env_ids)
        if not hasattr(self, "_lidar_frame_buf") or self._lidar_frame_buf is None:
            # Guard: _reset_idx can fire during parent __init__ before our __init__ runs.
            return
        if env_ids is None:
            self._lidar_frame_buf.zero_()
            self._lidar_stack_needs_fill.fill_(True)
        else:
            self._lidar_frame_buf[env_ids] = 0.0
            self._lidar_stack_needs_fill[env_ids] = True

        # Occupancy accumulator: drop the map and re-anchor the pose reference to the freshly
        # placed robot.  Zeroing alone would suffice for correctness (warping zeros yields zeros
        # regardless of the pose delta), but a stale reference would make the first transported
        # frame after a reset meaningless once the map refills.
        if hasattr(self, "_lidar_grid_acc"):
            origin, yaw = self._grid_frame_pose()
            if env_ids is None:
                self._lidar_grid_acc.zero_()
                self._lidar_grid_prev_pos.copy_(origin)
                self._lidar_grid_prev_yaw.copy_(yaw)
            else:
                self._lidar_grid_acc[env_ids] = 0.0
                self._lidar_grid_prev_pos[env_ids] = origin[env_ids]
                self._lidar_grid_prev_yaw[env_ids] = yaw[env_ids]

        # Rolling store: drop the map, re-snap its lattice to the freshly placed robot and clear
        # the held readout.  Leaving a stale snap would make the first scroll after a reset shift
        # a map that no longer corresponds to anything.
        if getattr(self, "_lidar_store_shape", None) is not None:
            # Own call to ``_grid_frame_pose`` rather than the ``origin`` the warp block above
            # binds: that block is guarded by ``hasattr(self, "_lidar_grid_acc")``, so gating the
            # warp allocation later would silently leave this reading a stale or unbound name.
            r_origin, _ = self._grid_frame_pose()
            snap = self._snap_origin(r_origin)
            if env_ids is None:
                self._lidar_grid_store.zero_()
                self._lidar_store_snap.copy_(snap)
                self._lidar_store_readout.zero_()
            else:
                self._lidar_grid_store[env_ids] = 0.0
                self._lidar_store_snap[env_ids] = snap[env_ids]
                self._lidar_store_readout[env_ids] = 0.0

        # Reset push counter for sensor-rate cadence (only allocated when flag=True).
        # Re-initialise to push_every (not 0) so reset envs push on their very first step,
        # matching the sensor's _is_outdated=True-on-reset semantics.
        if hasattr(self, "_lidar_push_ctr"):
            if env_ids is None:
                self._lidar_push_ctr.fill_(self._lidar_push_every)
            else:
                self._lidar_push_ctr[env_ids] = self._lidar_push_every

    # ------------------------------------------------------------------
    # R2 helpers
    # ------------------------------------------------------------------

    def _compute_range_image(self, distances: torch.Tensor, hit_valid: torch.Tensor) -> torch.Tensor:
        """Project (N, R) sensor distances + validity mask to (N, 2, H, W) range image.

        Projection:
            az  = atan2(y, x) % 2π  →  az_bin ∈ [0, W)
            el  = atan2(z, √(x²+y²)) →  el_bin ∈ [0, H) over measured elevation span
            bin = el_bin * W + az_bin        (R,)

        Scatter:
            range grid  init = 1.0  (empty bin → range_norm = 1.0)
            mask  grid  init = 0.0  (empty bin → no hit)
            scatter_reduce amin for range (closest hit per bin wins)
            scatter_reduce amax for mask  (1 if any hit maps to this bin)

        Elevation span:
            Derived from actual body-local ray_directions each step — not from the
            Mid-360 datasheet (−7° / +52°) because the dome-down ⊗ pitch-30° mount
            offset moves the pattern into a different body-frame span.
            Stored on self._lidar_el_min_deg / _lidar_el_max_deg for diagnostics.

        Args:
            distances:  (N, R) float32, sensor-measured distances in metres.
                        Miss and dropout already stored as max_distance (40 m).
            hit_valid:  (N, R) bool, True = genuine hit (not miss, dropout, occluded).

        Returns:
            (N, 2, H, W) float32.  ch0 = range_norm, ch1 = hit_mask.
        """
        N = distances.shape[0]
        H = self.cfg.lidar_image_h
        W = self.cfg.lidar_image_w
        max_range: float = self.cfg.lidar_max_range

        # --- Per-step bin map from current body-local ray directions -----------
        # ray_directions: warp ProxyArray; torch view is body-local (ray_alignment="base").
        # (R, 3) with the static core pattern — env-identical, so one bin map serves all envs.
        # (N, R, 3) with Mid360RollingLidarSensor — every env holds its own window, so the bin
        # map must be computed per env.
        dirs = self._mid360.ray_directions.torch

        az = torch.atan2(dirs[..., 1], dirs[..., 0]) % (2.0 * math.pi)  # [0, 2π)
        az_bin = (az / (2.0 * math.pi) * W).long().clamp(0, W - 1)

        el = torch.atan2(dirs[..., 2], torch.sqrt(dirs[..., 0] ** 2 + dirs[..., 1] ** 2))
        # Global min/max across every env and ray, so all envs share one elevation scale and
        # their range images stay mutually comparable.
        # Caveat for a future rolling + range-image arm: with per-env rolling windows this span
        # is re-derived from a different subset of the pattern each frame, so the row-to-angle
        # mapping is no longer stationary across time. Pin it to a constant span before pairing
        # the rolling sensor with the range-image representation.
        el_min = el.min()
        el_max = el.max()
        # Store for external diagnostics.
        self._lidar_el_min_deg = float(el_min.item() * 180.0 / math.pi)
        self._lidar_el_max_deg = float(el_max.item() * 180.0 / math.pi)

        el_bin = ((el - el_min) / (el_max - el_min + 1e-8) * H).long().clamp(0, H - 1)
        ray_bin = el_bin * W + az_bin  # (N, R) or (R,) flat index in [0, H*W)
        bin_idx = ray_bin if ray_bin.dim() == 2 else ray_bin.unsqueeze(0).expand(N, -1)  # (N, R)

        # --- Scatter into (N, H*W) grids ----------------------------------------
        # range_norm_flat: normalised distance for hits, 1.0 for misses (= empty default).
        dist_norm = distances.clamp(0.0, max_range) / max_range  # (N, R)
        range_norm_flat = torch.where(hit_valid, dist_norm, torch.ones_like(dist_norm))

        # Range grid: init=1.0 so empty bins stay at range_norm=1.0.
        range_grid = torch.ones(N, H * W, device=self.device, dtype=torch.float32)
        range_grid.scatter_reduce_(1, bin_idx, range_norm_flat, reduce="amin", include_self=True)

        # Mask grid: init=0.0 so empty bins stay at 0.
        mask_flat = hit_valid.float()
        mask_grid = torch.zeros(N, H * W, device=self.device, dtype=torch.float32)
        mask_grid.scatter_reduce_(1, bin_idx, mask_flat, reduce="amax", include_self=True)

        # Stack channels: (N, C=2, H, W) — ch0=range_norm, ch1=hit_mask.
        img = torch.stack(
            [range_grid.view(N, H, W), mask_grid.view(N, H, W)],
            dim=1,
        )  # (N, 2, H, W)
        return img

    @staticmethod
    def _mirror_range_image(img: torch.Tensor) -> torch.Tensor:
        """Horizontal flip of a range image for L/R symmetry data-augmentation.

        Approximates az → −az by flipping the W (azimuth) axis.  There is a half-bin
        offset vs the exact forward-beam convention — negligible for conv-based encoders.

        NOT active during training.  To be enabled in the symmetry aug pass:
            aug_obs = self._mirror_range_image(
                self._lidar_frame_buf.reshape(N, K, 2, H, W)
            ).reshape(N, -1)

        Args:
            img: (..., H, W) range image tensor (any leading dims).

        Returns:
            (..., H, W) with W axis flipped.
        """
        return torch.flip(img, dims=[-1])

